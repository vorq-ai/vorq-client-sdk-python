"""v2 signing — cross-language parity against the contracts' own committed vectors.

`tests/vectors/signing-v3.json` is generated by
`vorq-evm-contracts/test/Vectors.t.sol`, which reproduces the devnet's
deterministic deployment in-process, derives each digest from the case's own
published EIP-712 payload, and hands every signature to the deployed contract,
which must accept it before a byte is written. So it is the authority this Python
signer is checked against, and nothing here restates a digest, a separator or a
type table on the page: every expected value is read out of the file.

The one thing the file cannot check is *which deployment* a signer thinks it is
signing for, because a wrong `verifyingContract` produces a signature that
recovers to a stranger rather than an error. `TestDomainSeparation` is that
check, built from the file's own registry addresses.
"""

