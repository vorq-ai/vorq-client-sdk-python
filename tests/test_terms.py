class TestSessionVector:
    """The off-chain auth artifact — no contract, three spellings across the repos.
    Its `chainId` is the deployment's, announced by `GET /auth/nonce`: a browser
    wallet only signs a typed-data domain on the chain it is switched to, so the
    old pin at 1 locked every real wallet out. A session is still never submitted
    anywhere, and the coordinator verifies it against a nonce minted in its own
    database, which is what prevents replay. Version `1` and a domain with no
    `verifyingContract` keep it in a namespace the chain will never accept, so a
    captured login can never be replayed as an op.
    """

    def test_the_domain_is_bound_to_the_vectors_chain(self):
        domain = CASES["session"]["typed_data"]["domain"]
        assert vorq_domain(VECTORS["chain_id"]) == domain
        assert domain["chainId"] == VECTORS["chain_id"]
        assert domain["version"] == "1"
        assert "verifyingContract" not in domain

    def test_the_digest_matches(self):
        assert _digest(vorq_domain(VECTORS["chain_id"]), SESSION_TYPES, message("session")) == CASES["session"]["digest"]

    def test_the_signature_recovers_to_the_vectors_signer(self):
        signable = encode_typed_data(vorq_domain(VECTORS["chain_id"]), SESSION_TYPES, message("session"))
        assert Account.recover_message(signable, signature=CASES["session"]["signature"]) == (
            CASES["session"]["signer"]
        )

    def test_sign_nonce_round_trips(self):
        signer = WalletSigner(Account.create().key.hex())
        sig = signer.sign_nonce(raw("session")["nonce"], VECTORS["chain_id"])
        signable = encode_typed_data(
            vorq_domain(VECTORS["chain_id"]), SESSION_TYPES, {"address": signer.address, "nonce": raw("session")["nonce"]}
        )
        assert Account.recover_message(signable, signature=sig) == signer.address

    def test_the_session_domain_is_not_an_op_domain(self):
        """Version 1 against the ops' version 2, so the two namespaces cannot meet."""
        assert vorq_domain(CTX.chain_id)["version"] != order_domain(CTX)["version"]


class TestTheVectorsBelongToThisDeployment:
    def test_the_file_says_which_chain_it_is_for(self):
        assert VECTORS["chain_id"] == CTX.chain_id

    def test_the_addresses_are_the_ones_every_digest_was_built_over(self):
        assert order_domain(CTX)["verifyingContract"] == ADDRESSES["job_registry"]
        assert payment_domain(CTX)["verifyingContract"] == ADDRESSES["payment_token"]

    def test_the_c_values_are_the_containers(self):
        """The vectors' `c` values are lifted from `container-v1.json` (Q14).

        A container test and an order test therefore chain end to end rather than
        starting from an invented commitment.
        """
        containers = json.loads(
            (Path(__file__).parent / "vectors" / "container-v1.json").read_text()
        )
        known = {case["c"].lower() for case in containers["cases"]}
        for name in ("order-designated", "order-open"):
            assert raw(name)["c"].lower() in known
