class TestRateWire:
    """The terms hold atomic rates (what is signed); the wire carries them as USD strings."""

    @pytest.mark.parametrize("field", ["rate_in", "rate_out"])
    def test_past_uint128_is_refused(self, field):
        with pytest.raises(ValidationError, match=f"vorq.{field} must be an integer in"):
            OrderTerms(**{**_terms_of("order-open").__dict__, field: 2**128})

    def test_rates_go_out_as_canonical_usd_strings(self):
        terms = OrderTerms(**{**_terms_of("order-open").__dict__,
                              "rate_in": 50_000, "rate_out": 2**128 - 1})
        wire = terms.to_wire(owner="0x" + "11" * 20, job_id="0x" + "22" * 32, signature="0x",
                             decimals=6)
        assert wire["rate_in"] == "0.05"
        assert wire["rate_out"] == "340282366920938463463374607431768.211455"
        assert type(wire["model_id"]) is int and type(wire["expires_at"]) is int


