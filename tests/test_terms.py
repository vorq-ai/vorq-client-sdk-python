class TestTypeTables:
    """Direct list equality against the published tables.

    The file carries the actual `[{name, type}, ...]` tables the contract's own
    accepted signatures were built from — not a derived type string — so an SDK
    table that disagrees is caught here without rebuilding a string to compare.
    """

