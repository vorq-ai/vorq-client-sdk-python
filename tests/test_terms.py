#: The payment token's own EIP-712 name and version, as the file publishes them.
#: They differ per network, which is why the node states them rather than the SDK.
TOKEN = DOMAINS["payment_token"]["domain"]

#: The chain context those vectors belong to, built from the file's own
#: `addresses` block — including `ask_registry`, which this SDK signs nothing
#: against but must carry so a mix-up is statable rather than invisible.
CTX = ChainContext(
    chain_id=VECTORS["chain_id"],
    job_registry=ADDRESSES["job_registry"],
    provider_registry=ADDRESSES["provider_registry"],
    ask_registry=ADDRESSES["ask_registry"],
    usdc=ADDRESSES["payment_token"],
    decimals=6,
    token_domain=TokenDomain(TOKEN["name"], TOKEN["version"]),
)

#: The vectors' own client wallet — anvil index 4. Which key signs is free for
#: the orders, the cancel and the session, where recovery only has to return
#: *this* address. It is not free for `payment-authorization`: `from` is a signed
#: member, so only the wallet the vector names there reaches its digest at all.
VECTOR_KEY = "0x47e179ec197488593b187f80a00eb0da91f1b9d0b13f8733639f19c30a34926a"


def raw(name: str) -> dict:
    """A case's message exactly as the file carries it, before any decoding."""
    return CASES[name]["typed_data"]["message"]


def extra(name: str) -> dict:
    return CASES[name]["extra"]


def _b(value: str) -> bytes:
    return bytes.fromhex(value[2:] if value.startswith("0x") else value)


def _terms_of(name: str) -> OrderTerms:
    m = raw(name)
    return OrderTerms(
        c=_b(m["c"]),
        model_id=m["modelId"],
        sla_secs=m["slaSecs"],
        rate_in=int(m["rateIn"]),
        rate_out=int(m["rateOut"]),
        units_in=m["unitsIn"],
        units_out=m["unitsOut"],
        designated=m["designated"],
        expires_at=m["expiresAt"],
    )


def _digest(domain: dict, types: dict, msg: dict) -> str:
    """The EIP-712 digest eth-account would sign, as 0x hex."""
    signable = encode_typed_data(domain, types, msg)
    return "0x" + keccak(b"\x19" + signable.version + signable.header + signable.body).hex()


def recover_against_vector(name: str, signature: str) -> str:
    """Recover ``signature`` using the **vector's own** published payload.

    A digest this SDK built differently — a renamed member, a reordered table, a
    `version` dropped from the token's domain — recovers a different address
    rather than raising, which is the whole failure mode the file exists to
    catch. Rebuilding the payload from `vorq/` here instead would prove only
    that this test and that module agree with each other.
    """
    case = CASES[name]["typed_data"]
    return Account.recover_message(
        encode_typed_data(case["domain"], local_types(name), message(name)),
        signature=signature,
    )


# -- the chain context ---------------------------------------------------------


class TestChainContext:
    """Q6: all four contracts, and the fourth is the one that bites."""

    WIRE = {
        "chain_id": VECTORS["chain_id"],
        "contracts": {
            "job_registry": ADDRESSES["job_registry"],
            "provider_registry": ADDRESSES["provider_registry"],
            "ask_registry": ADDRESSES["ask_registry"],
            "usdc": ADDRESSES["payment_token"],
        },
        "decimals": 6,
        "token_domain": {"name": TOKEN["name"], "version": TOKEN["version"]},
        # On the body and deliberately unread: this SDK does not price gas, does
        # not wait on a head, and assembles no transaction (Q19).
        "head_block": 128,
        "block_time_ms": 1000,
        "fee_bps": 100,
    }

    def test_it_carries_all_four_addresses(self):
        ctx = ChainContext.from_wire(self.WIRE)
        assert ctx.contracts == self.WIRE["contracts"]
        assert set(ctx.contracts) == set(CONTRACT_FIELDS)
        assert CONTRACT_FIELDS == (
            "job_registry", "provider_registry", "ask_registry", "usdc"
        )

    def test_it_carries_the_tokens_decimals_and_its_own_domain(self):
        """Both are the node's to state: they differ per network, and the second
        is signed over — a wrong `version` recovers to a stranger."""
        ctx = ChainContext.from_wire(self.WIRE)
        assert ctx.decimals == 6
        assert ctx.token_domain == TokenDomain(TOKEN["name"], TOKEN["version"])

    @pytest.mark.parametrize("missing", ["decimals", "token_domain"])
    def test_a_body_without_the_token_is_refused(self, missing):
        wire = {k: v for k, v in self.WIRE.items() if k != missing}
        with pytest.raises(ValidationError, match=missing):
            ChainContext.from_wire(wire)

    @pytest.mark.parametrize("domain", [{"name": "USDC"}, {"name": "", "version": "2"},
                                        {"name": "USDC", "version": ""}, "USDC"])
    def test_a_half_stated_token_domain_is_refused(self, domain):
        """Half a domain is worse than none: it signs, and it recovers to nobody."""
        with pytest.raises(ValidationError, match="token_domain"):
            ChainContext.from_wire({**self.WIRE, "token_domain": domain})

    @pytest.mark.parametrize(
        "missing",
        ["job_registry", "provider_registry", "ask_registry", "usdc"],
    )
    def test_a_missing_contract_is_refused_by_name(self, missing):
        wire = {**self.WIRE, "contracts": {
            k: v for k, v in self.WIRE["contracts"].items() if k != missing
        }}
        with pytest.raises(ValidationError, match=missing):
            ChainContext.from_wire(wire)

    def test_provider_registry_is_carried_even_though_this_sdk_signs_no_registry_op(self):
        """It is the address the plan's own type dropped (Q6).

        Nothing in the client signs a ProviderRegistry op — but the VORQ domains
        are otherwise identical, so a context without it cannot state the
        difference, and a consumer that guessed would produce a signature that
        recovers to somebody else instead of failing.
        """
        ctx = ChainContext.from_wire(self.WIRE)
        assert ctx.provider_registry == ADDRESSES["provider_registry"]
        assert ctx.provider_registry != ctx.job_registry

    def test_it_is_frozen(self):
        ctx = ChainContext.from_wire(self.WIRE)
        with pytest.raises(Exception):
            ctx.job_registry = ADDRESSES["payment_token"]  # type: ignore[misc]

    def test_a_body_with_no_contracts_block_is_refused(self):
        with pytest.raises(ValidationError):
            ChainContext.from_wire({"chain_id": VECTORS["chain_id"]})

    def test_a_malformed_address_is_refused_by_name(self):
        wire = {**self.WIRE, "contracts": {**self.WIRE["contracts"], "usdc": "0xdead"}}
        with pytest.raises(ValidationError, match="usdc"):
            ChainContext.from_wire(wire)


